// Generates src/styles/tokens.css from design-source/tokens.json.
// Runs automatically before `dev` and `build` (see package.json "predev"/"prebuild").
//
// Mapping:
//   color.tokens[]   -> --{name}                 (light in :root, dark under [data-theme="dark"])
//   shadow.tokens[]  -> --{name}                 (themed, same as colours)
//   spacing.tokens[] -> --{name}                 (e.g. --space-5: 24px)
//   radius.tokens[]  -> --{name}                 (e.g. --radius-pill: 999px)
//   type.families    -> --font-{family}
//   type.groups[].styles[] -> --type-{style}-size / -line / -weight / -tracking
//
// The default theme follows `prefers-color-scheme`; an explicit choice sets
// data-theme="light" | "dark" on <html>, which wins over the media query.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'design-source/tokens.json'), 'utf8'));
const outFile = resolve(root, 'src/styles/tokens.css');

// Values the page layer (site.css) uses that are not in tokens.json yet.
// Kept here, clearly marked, so they live in one place. See README "Open items".
const EXTENSIONS = {
  'shadow-photo': {
    light: 'drop-shadow(0 18px 30px rgba(27,31,59,0.22))',
    dark: 'drop-shadow(0 18px 30px rgba(0,0,0,0.5))',
  },
  'shadow-card-hover': {
    light: '0 24px 56px rgba(62,52,140,0.16)',
    dark: '0 24px 56px rgba(0,0,0,0.55)',
  },
};

const themed = [...tokens.color.tokens, ...tokens.shadow.tokens].map((t) => [t.name, t.value]);
for (const [name, value] of Object.entries(EXTENSIONS)) themed.push([name, value]);

const decl = (mode) => themed.map(([name, v]) => `  --${name}: ${v[mode]};`).join('\n');

const statics = [];
for (const [fam, stack] of Object.entries(tokens.type.families))
  statics.push(`  --font-${fam}: ${stack};`);
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    statics.push(`  --type-${s.name}-size: ${s.fontSize};`);
    statics.push(`  --type-${s.name}-line: ${s.lineHeight};`);
    statics.push(`  --type-${s.name}-weight: ${s.fontWeight};`);
    if (s.letterSpacing) statics.push(`  --type-${s.name}-tracking: ${s.letterSpacing};`);
  }
}
for (const t of tokens.spacing.tokens) statics.push(`  --${t.name}: ${t.value};`);
for (const t of tokens.radius.tokens) statics.push(`  --${t.name}: ${t.value};`);

const css = `/* GENERATED by scripts/build-tokens.mjs from design-source/tokens.json. Do not edit. */
/* ${tokens.name} v${tokens.version} */

:root {
${statics.join('\n')}
}

:root,
:root[data-theme='light'] {
  color-scheme: light;
${decl('light')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${decl('dark').replace(/^ {2}/gm, '    ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${decl('dark')}
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, css);
console.log(`tokens.css written (${themed.length} themed, ${statics.length} static tokens)`);
